/** 为全部 Boss 生成专属贴图（机头朝上，运行时会垂直翻转面向玩家） */
export function ensureBossArt(scene: Phaser.Scene): void {
  for (const id of Object.keys(bossConfigs)) {
    const draw = BOSS_DRAWERS[id] ?? drawMechanicalEagle;
    canvasArt(scene, `boss_${id}`, W, H, draw);
  }
}

